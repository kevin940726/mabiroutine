import { useCallback, useMemo, useState } from "react";
import entriesJson from "@/data/whatsNew.generated.json";

/** The changelog drawer's state: which releases are newer than what this
 *  device has read, how the menu row words that, and what the drawer shows once
 *  it opens.
 *
 *  The marker is device-local, like the theme, and deliberately NOT part of
 *  `useAppStore`: reading a changelog is not progress, and syncing it would let
 *  one device's read hide another device's unread copy. Nothing here touches the
 *  save schema, so no `version` bump.
 *
 *  `src/data/whatsNew.generated.json` is generated by `scripts/whats-new.mjs`
 *  from `CHANGELOG-zh_TW.md` (never hand-edit it); `--check` keeps the two in
 *  step. This module only reads it. */

/** `### 新功能` / `### 修正` as the parser records them. */
export type WhatsNewKind = "feature" | "fix";

/** One bullet. `release` is the marker text — the release's id — and `date` is
 *  the heading date (`YYYY-MM-DD`). */
export type WhatsNewEntry = {
  release: string;
  date: string;
  kind: WhatsNewKind;
  text: string;
};

/** One release: its marker as the id, its heading date, its bullets in file
 *  order. */
export type Release = {
  id: string;
  date: string;
  entries: WhatsNewEntry[];
};

/** Releases that share a heading date, newest day first. Two releases shipped
 *  on one day share one heading and keep their own bullets. */
export type DateGroup = {
  date: string;
  releases: Release[];
};

/** The marker of the newest release this device has opened. A plain string
 *  rather than JSON: the id is all there is to store. */
const SEEN_KEY = "mabiroutine:whatsnew-seen";

/** The generated JSON declares `kind` as `string`, so the cast is where the
 *  union is asserted — same shape as `trackerJson as Task[]` in App. The
 *  parser's own validation plus the gate (JSON equals a fresh parse) are what
 *  make the assertion safe. */
const ENTRIES = entriesJson as WhatsNewEntry[];

/** `2026-10-20` -> `10/20`. The date is the release's calendar day (the Taipei
 *  cut date, as written in the heading), not an instant, so it is formatted
 *  from the string rather than through a `Date` that could shift it. Anything
 *  unexpected comes back unchanged rather than as `NaN/NaN`. */
export function formatMd(date: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(date);
  return m ? `${m[2]}/${m[3]}` : date;
}

/** The date a marker starts with, or null when it does not start with one.
 *  This is the fallback used when a marker no longer names a release. */
export function markerDate(marker: string): string | null {
  const m = /^(\d{4}-\d{2}-\d{2})/.exec(marker);
  return m ? m[1] : null;
}

/** Consecutive entries with the same marker are one release. The JSON is
 *  written in file order, newest first, so a release's bullets are contiguous
 *  and the first group is the newest release. */
export function releasesOf(entries: readonly WhatsNewEntry[]): Release[] {
  const out: Release[] = [];
  for (const entry of entries) {
    const last = out[out.length - 1];
    if (last && last.id === entry.release) last.entries.push(entry);
    else out.push({ id: entry.release, date: entry.date, entries: [entry] });
  }
  return out;
}

/** Fold releases into their heading dates, preserving the input order (newest
 *  first). Same assumption as `releasesOf`: the source is already sorted. */
export function groupByDate(releases: readonly Release[]): DateGroup[] {
  const out: DateGroup[] = [];
  for (const release of releases) {
    const last = out[out.length - 1];
    if (last && last.date === release.date) last.releases.push(release);
    else out.push({ date: release.date, releases: [release] });
  }
  return out;
}

export function readSeen(): string | null {
  try {
    const raw = localStorage.getItem(SEEN_KEY);
    return raw && raw.trim() ? raw : null;
  } catch {
    // Private mode / blocked storage: behaves like a first visit, which shows
    // the latest release and never a dot.
    return null;
  }
}

export function writeSeen(release: string): void {
  try {
    localStorage.setItem(SEEN_KEY, release);
  } catch {
    // Private mode: the marker lasts this visit. The drawer still opened; the
    // row just reads 最新 next time, which is the harmless direction.
  }
}

export function latestRelease(): Release | null {
  return releasesOf(ENTRIES)[0] ?? null;
}

/** What the menu row says, and which releases are unread.
 *
 *  - `first` — no marker (a new device, cleared storage): the row says
 *    `最新 · MM/DD`. A badge here would announce content the user never missed,
 *    so there is no unread set to report; the drawer still shows the latest
 *    release.
 *  - `unread` — every release newer than the marker, newest first. The count is
 *    releases, not bullets.
 *  - `read` — the marker is the newest release (or newer than every entry). */
export type WhatsNewSummary = {
  state: "first" | "unread" | "read";
  /** Newer than the marker. Empty unless `state === "unread"`. */
  unread: Release[];
  /** Every release, newest first. */
  releases: Release[];
  /** The menu row's status text. */
  label: string;
};

export function summaryFor(seen: string | null, entries: readonly WhatsNewEntry[] = ENTRIES): WhatsNewSummary {
  const releases = releasesOf(entries);
  const latest = releases[0];

  if (!latest) return { state: "read", unread: [], releases, label: "已讀到最新" };

  if (seen === null) {
    return { state: "first", unread: [], releases, label: `最新 · ${formatMd(latest.date)}` };
  }

  const at = releases.findIndex((r) => r.id === seen);
  let unread: Release[];
  if (at >= 0) {
    unread = releases.slice(0, at);
  } else {
    // The marker no longer names a release: its heading was reworded, or the
    // release was rewritten. Fall back to the date in the marker rather than
    // the zh heading, so the window still starts where the reader left off.
    // `>=` on purpose: a release added later on the SAME day is
    // indistinguishable from the relabelled one, and re-showing one already
    // read release is repaid by the marker moving on the next open, while a
    // strict `>` would hide the same-day release for good.
    const date = markerDate(seen);
    unread = date ? releases.filter((r) => r.date >= date) : [];
  }

  if (!unread.length) return { state: "read", unread, releases, label: "已讀到最新" };
  return {
    state: "unread",
    unread,
    releases,
    label: `${formatMd(unread[0].date)} · ${unread.length} 則未讀`,
  };
}

/** How long the trigger's dot keeps pulling: two weeks of Taipei calendar days.
 *  After that the row's own sentence carries the status and the dot stops
 *  asking — it means "there is something recent", not a debt. */
export const DOT_WINDOW_DAYS = 14;

/** `YYYY-MM-DD` in Asia/Taipei.
 *
 *  A release's date is the Taipei cut date written in its heading, so "today"
 *  has to be the same calendar: the device's zone would make a release dated
 *  today in Taipei look a day old west of it, and UTC would do the same for the
 *  first six hours of a Taipei day. */
const TAIPEI_DAY = new Intl.DateTimeFormat("en-CA", {
  timeZone: "Asia/Taipei",
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
});

export function taipeiDate(at: number | Date = Date.now()): string {
  return TAIPEI_DAY.format(at);
}

/** Whole calendar days from `date` to `today`, both `YYYY-MM-DD`. Built from
 *  UTC midnights so the difference is an exact day count, not 13.96 days of
 *  wall-clock, and null when either string is not a date. */
function daysBetween(date: string, today: string): number | null {
  const from = /^(\d{4})-(\d{2})-(\d{2})$/.exec(date);
  const to = /^(\d{4})-(\d{2})-(\d{2})$/.exec(today);
  if (!from || !to) return null;
  const a = Date.UTC(Number(from[1]), Number(from[2]) - 1, Number(from[3]));
  const b = Date.UTC(Number(to[1]), Number(to[2]) - 1, Number(to[3]));
  return (b - a) / 86_400_000;
}

/** Whether the ☰ trigger shows its amber dot. All three must hold:
 *
 *  - `state === "unread"`: a first visit missed nothing (no dot on install), and
 *    a caught-up device has nothing to be pulled to;
 *  - some unread bullet is a `feature`: amber means "there is something to try",
 *    so a fixes-only release never dots — a repair is not an invitation;
 *  - the newest unread release is at most `DOT_WINDOW_DAYS` old. The window is
 *    inclusive: exactly 14 Taipei days still dots, and it lets go on the 15th.
 *    A future date (a release dated ahead of the device's clock) counts as
 *    recent rather than as a broken date.
 *
 *  The dot is 6px, unnumbered and `aria-hidden`; the row's sentence keeps the
 *  count either way, and this is the only pull the trigger ever carries — never
 *  sync failure or a ready update. */
export function dotFor(summary: WhatsNewSummary, today: string): boolean {
  if (summary.state !== "unread") return false;
  const newest = summary.unread[0];
  if (!newest) return false;
  if (!summary.unread.some((r) => r.entries.some((e) => e.kind === "feature"))) return false;
  const age = daysBetween(newest.date, today);
  return age !== null && age <= DOT_WINDOW_DAYS;
}

export type WhatsNewView = {
  /** Date groups, newest first; each release keeps its own bullets. */
  groups: DateGroup[];
  /** Whether to print the caught-up line and the archive link. */
  caughtUp: boolean;
};

/** The drawer's content for a summary. The unread window is what the reader
 *  asked for; with no marker and with nothing unread, it is the latest release
 *  only — never the whole history, which would turn a first visit into an
 *  archive dump. */
export function viewFor(summary: WhatsNewSummary): WhatsNewView {
  const shown = summary.state === "unread" ? summary.unread : summary.releases.slice(0, 1);
  return { groups: groupByDate(shown), caughtUp: summary.state === "read" };
}

/** Row state plus the drawer. Mounted in `AppMenu`, whose root outlives the
 *  dropdown: putting the drawer inside the menu content would unmount it the
 *  moment the menu closes, which is exactly when the click opens it. */
export function useWhatsNew() {
  const [seen, setSeen] = useState<string | null>(readSeen);
  const summary = useMemo(() => summaryFor(seen), [seen]);
  // A SNAPSHOT taken when the drawer opens. Opening writes the marker, so
  // recomputing the view from `seen` afterwards would empty the list the click
  // was asking for.
  const [view, setView] = useState<WhatsNewView>(() => viewFor(summaryFor(readSeen())));
  const [open, setOpen] = useState(false);

  const openDrawer = useCallback(() => {
    setView(viewFor(summaryFor(readSeen())));
    setOpen(true);
    // Opening is the read (not closing, not per bullet): the row and the dot
    // settle to 已讀到最新 while the drawer is still up.
    const latest = latestRelease();
    if (!latest) return;
    writeSeen(latest.id);
    setSeen(latest.id);
  }, []);

  return { summary, view, open, openDrawer, onOpenChange: setOpen };
}
